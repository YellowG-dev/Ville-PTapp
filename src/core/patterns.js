// Swap options for one prescribed exercise. The list:
// - drops the variant matching what is already prescribed (no "swap" to itself)
// - drops variants already prescribed elsewhere the same day
// - on a no-gym day, keeps only bodyweight/band
export function variantsFor(patternId, { prescribedName, alsoToday = [], noGym = false } = {}) {
  const list = PATTERNS[patternId];
  if (!list) return [];
  const norm = (s) => (s || "").trim().toLowerCase();
  const blocked = new Set([norm(prescribedName), ...alsoToday.map(norm)]);
  return list
    .filter((v) => !blocked.has(norm(v.name)))
    .filter((v) => (noGym ? NOGYM_EQUIP.includes(v.equip) : true));
}
